function nameIn(text: string): string | null {
  const m = /(?:ich hei(?:ß|ss)e|mein name ist|nenn mich|^ich bin(?: der| die)?)\s+([A-Za-zÀ-ÿ-]{2,20})/i.exec(text.trim());
  if (!m) return null;
  const n = m[1];
  if (/^(nicht|so|sehr|gut|ok|schlecht|hier|zuruck|zurück|fertig|mude|müde|ein|eine|neu|anfanger|anfänger|traurig|froh|bereit|sicher|noch|wirklich|verwirrt|dran)$/i.test(n)) return null;
  return n[0].toUpperCase() + n.slice(1).toLowerCase();
}

