const RULES: [string, RegExp][] = RAW.map(([k, r]) => [k, new RegExp(r.source.replace(/й/g, 'и').replace(/ё/g, 'е'), r.flags)]);

function nameIn(text: string): string | null {
  const m = /(?:меня зовут|мое имя|моё имя|зови меня)\s+([A-Za-zА-Яа-яЁё-]{2,20})/i.exec(text.trim());
  if (!m) return null;
  const n = m[1];
  if (/^(не|так|очень|просто)$/i.test(n)) return null;
  return n[0].toUpperCase() + n.slice(1).toLowerCase();
}

