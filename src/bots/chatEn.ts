/** Tout le chat d'une langue (hors francais, qui est dans chat.ts) */
export interface ChatPack {
  /** Intentions : texte normalise (minuscules, sans accents ni apostrophes) */
  rules: [string, RegExp][];
  /** Debut de question */
  question: RegExp;
  /** Prenom annonce par le joueur */
  nameIn: (text: string) => string | null;
  /** Question sur les regles ("comment bouge…") */
  rulesQ: RegExp;
  phase: typeof PHASE_EN;
  tips: typeof TIPS_EN;
  ruleFacts: [RegExp, string][];
  s: typeof S_EN;
  common: Lines;
  personas: Record<string, Lines>;
  /** Abreviations facon SMS (Pip, Hugo) */
  sms: [RegExp, string][];
  pipLaugh: string;
  hugoSlang: string[];
  /** Virgule decimale (3,5) */
  comma: boolean;
  /** Debut de phrase a ne pas mettre en minuscule apres le prenom ("I …") */
  keepCase?: RegExp;
}

