/** Prenom annonce en anglais ("my name is Sam", "call me Sam", "I'm Sam") */
export function nameInEn(text: string): string | null {
  const m = /(?:my name(?:'|’)?s|my name is|call me|i(?:'|’)?m called|^i(?:'|’| a)?m)\s+([A-Za-zÀ-ÿ-]{2,20})/i.exec(text.trim());
  if (!m) return null;
  const n = m[1];
  if (/^(not|so|very|fine|good|ok|okay|bad|here|back|done|sorry|tired|bored|a|an|the|just|going|trying|playing|winning|losing|scared|happy|sad|lost|ready|sure|new|still|really|confused)$/i.test(n)) return null;
  return n[0].toUpperCase() + n.slice(1).toLowerCase();
}

