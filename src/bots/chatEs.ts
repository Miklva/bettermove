function nameIn(text: string): string | null {
  const m = /(?:me llamo|mi nombre es|ll[aá]mame|^soy)\s+([A-Za-zÀ-ÿ-]{2,20})/i.exec(text.trim());
  if (!m) return null;
  const n = m[1];
  if (/^(muy|un|una|el|la|malo|mala|bueno|buena|nuevo|nueva|yo|de|tu|tan|bastante|principiante|humano|humana|feliz|triste)$/i.test(n)) return null;
  return n[0].toUpperCase() + n.slice(1).toLowerCase();
}

