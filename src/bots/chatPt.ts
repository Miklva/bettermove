function nameIn(text: string): string | null {
  const m = /(?:chamo-me|chamo me|o meu nome [ée]|chama-me|^sou o|^sou a)\s+([A-Za-zÀ-ÿ-]{2,20})/i.exec(text.trim());
  if (!m) return null;
  const n = m[1];
  if (/^(muito|um|uma|o|a|mau|bom|novo|nova|eu|de|tao|principiante|humano|humana|feliz|triste)$/i.test(n)) return null;
  return n[0].toUpperCase() + n.slice(1).toLowerCase();
}

